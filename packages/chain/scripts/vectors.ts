const receiptFields = (n: number, seed: string): ReceiptFields[] =>
  Array.from({ length: n }, (_, i) => ({
    callId: hash32(`${seed}:call:${i}`),
    budgetId: hash32(`${seed}:budget`),
    payee: i % 2 === 0 ? "api.seller.testnet" : "other.seller.testnet",
    amount: BigInt(1000 + i),
    cumulative: BigInt((1000 + i) * (i + 1)),
    requestHash: hash32(`${seed}:request:${i}`),
    timestampMs: 1_800_000_000_000n + BigInt(i),
    voucherSig: hash32(`${seed}:sig-a:${i}`) + hash32(`${seed}:sig-b:${i}`),
  }));

function merkleCases() {
  return [1, 2, 3, 4, 5, 7, 8, 16, 33].map((n) => {
    const batchId = hash32(`batch-${n}`);
    const fields = receiptFields(n, `tree-${n}`);
    const tree = buildReceiptTree(HUB, NETWORK, batchId, fields);
    return {
      name: `leaves_${n}`,
      hub: HUB,
      network: NETWORK,
      batch_id: batchId,
      receipts_in_leaf_order: tree.receipts.map((f, i) => ({
        call_id: f.callId,
        budget_id: f.budgetId,
        payee: f.payee,
        amount: f.amount.toString(),
        cumulative: f.cumulative.toString(),
        request_hash: f.requestHash,
        timestamp_ms: f.timestampMs.toString(),
        voucher_sig: f.voucherSig,
        borsh_hex: toHex(receiptLeafPreimage(HUB, NETWORK, batchId, f)),
        leaf_hex: tree.leaves[i]!,
        proof: tree.proofOf(f.callId),
      })),
      root: tree.root,
    };
  });
}

function nodeCases() {
  const a = hash32("node-a");
  const b = hash32("node-b");
  return [
    { name: "ordered", left: a < b ? a : b, right: a < b ? b : a, node_hex: hashPair(a, b) },
    { name: "reversed", left: a < b ? b : a, right: a < b ? a : b, node_hex: hashPair(b, a) },
  ];
}

function nettingCases() {
  const cases = [
    {
      name: "offset_a_owes_b_10_b_owes_a_7",
      lines: [
        { owner: "a.testnet", payee: "b.testnet", delta: 10n },
        { owner: "b.testnet", payee: "a.testnet", delta: 7n },
      ],
    },
    {
      name: "pure_creditor_and_aggregation",
      lines: [
        { owner: "a.testnet", payee: "s.testnet", delta: 2n },
        { owner: "a.testnet", payee: "t.testnet", delta: 3n },
      ],
    },
    {
      name: "zero_net_party_omitted",
      lines: [
        { owner: "z.testnet", payee: "m.testnet", delta: 5n },
        { owner: "m.testnet", payee: "z.testnet", delta: 5n },
        { owner: "c.testnet", payee: "b.testnet", delta: 1n },
      ],
    },
    { name: "self_payment", lines: [{ owner: "a.testnet", payee: "a.testnet", delta: 4n }] },
  ];
  return cases.map(({ name, lines }) => {
    const r = computeNetting(lines);
    return {
      name,
      lines: lines.map((l) => ({ owner: l.owner, payee: l.payee, delta: l.delta.toString() })),
      gross: r.gross.toString(),
      net: r.net.toString(),
      expected_net: r.entries.map((e) => ({ account: e.account, debit: e.debit.toString(), credit: e.credit.toString() })),
    };
  });
}

export function buildVectors(): Record<string, unknown> {
  return {
    keys: { note: NOTE, keys: Object.values(keys).map(keyView) },
    voucher: { note: NOTE, tag: VOUCHER_TAG, domain: VOUCHER_DOMAIN, cases: voucherCases() },
    budget: { note: NOTE, domain: BUDGET_DOMAIN, max_payees: MAX_PAYEES, cases: budgetCases() },
    checkout: { note: NOTE, tag: CHECKOUT_TAG, domain: CHECKOUT_DOMAIN, cases: checkoutCases() },
    merkle: {
      note: NOTE,
      domain: RECEIPT_DOMAIN,
      leaf_prefix: "00",
      node_prefix: "01",
      max_depth: MAX_MERKLE_DEPTH,
      node_cases: nodeCases(),
      cases: merkleCases(),
    },
    netting: { note: NOTE, max_claims: MAX_CLAIMS, max_payout_accounts: MAX_PAYOUT_ACCOUNTS, cases: nettingCases() },
    acceptance: {
      note: NOTE,
      about:
        "The node signs sha256 of `text` (UTF-8) with a receipt key when it accepts a call. settle_own rebuilds the text from the claim and checks the signature. Fields are joined with `|` in this order: domain, call_id, budget_id, payee, amount, cumulative, request_hash, timestamp_s, voucher_sig. call_id is sha256 of `call_domain|budget_id|payee|cumulative|request_hash`.",
      domain: ACCEPTANCE_DOMAIN,
      call_domain: CALL_DOMAIN,
      timestamp_unit: "seconds",
      max_receipt_keys: MAX_RECEIPT_KEYS,
      revoke_grace_ms: REVOKE_GRACE_MS.toString(),
      expiry_grace_ms: EXPIRY_GRACE_MS.toString(),
      cases: acceptanceCases(),
    },
    storage: {
      note: "Bytes of storage per hub record: key, value and the protocol's per-record overhead. Generated by packages/chain/scripts/gen-vectors.ts.",
      byte_cost_yocto: STORAGE_BYTE_COST.toString(),
      record_overhead_bytes: STORAGE_RECORD_BYTES,
      reserved_settle_own_bytes: RESERVED_SETTLE_OWN_BYTES,
      revoke_bytes: REVOKE_BYTES,
      cases: storageCases(),
    },
    errors: {
      note: "Every code the hub panics with, sorted. contracts-near/src/errors.rs ALL and HUB_ERRORS must both equal this list.",
      codes: [...HUB_ERRORS],
    },
  };
}
