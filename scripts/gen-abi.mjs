// Regenerates packages/protocol/src/abi.ts from the Foundry build output so TS and Solidity never drift.
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("..", import.meta.url).pathname;
const art = JSON.parse(readFileSync(`${root}contracts/out/ClearingHub.sol/ClearingHub.json`, "utf8"));
const mock = JSON.parse(readFileSync(`${root}contracts/out/MockStablecoin.sol/MockStablecoin.json`, "utf8"));
const fiat = JSON.parse(readFileSync(`${root}contracts/out/MockFiatToken.sol/MockFiatToken.json`, "utf8"));
const factory = JSON.parse(readFileSync(`${root}contracts/out/DepositFactory.sol/DepositFactory.json`, "utf8"));
const forwarder = JSON.parse(readFileSync(`${root}contracts/out/DepositForwarder.sol/DepositForwarder.json`, "utf8"));
const router = JSON.parse(readFileSync(`${root}contracts/out/PaymentRouter.sol/PaymentRouter.json`, "utf8"));
// EIP-3009 as FiatToken v2.2 exposes it, cut from the mock so the fragment always matches what the tests exercise.
const eip3009Names = new Set([
  "transferWithAuthorization",
  "receiveWithAuthorization",
  "cancelAuthorization",
  "authorizationState",
  "AuthorizationUsed",
  "AuthorizationCanceled",
]);
const eip3009 = mock.abi.filter((item) => eip3009Names.has(item.name));
if (eip3009.length !== 9) throw new Error(`expected 9 EIP-3009 ABI items in MockStablecoin, found ${eip3009.length}`);
const out = `// Generated by scripts/gen-abi.mjs from the Foundry build. Do not edit by hand.
export const clearingHubAbi = ${JSON.stringify(art.abi, null, 2)} as const;

export const clearingHubBytecode = ${JSON.stringify(art.bytecode.object)} as const;

export const mockStablecoinAbi = ${JSON.stringify(mock.abi, null, 2)} as const;

export const mockStablecoinBytecode = ${JSON.stringify(mock.bytecode.object)} as const;

export const mockFiatTokenAbi = ${JSON.stringify(fiat.abi, null, 2)} as const;

export const mockFiatTokenBytecode = ${JSON.stringify(fiat.bytecode.object)} as const;

export const depositFactoryAbi = ${JSON.stringify(factory.abi, null, 2)} as const;

export const depositFactoryBytecode = ${JSON.stringify(factory.bytecode.object)} as const;

export const depositForwarderAbi = ${JSON.stringify(forwarder.abi, null, 2)} as const;

export const paymentRouterAbi = ${JSON.stringify(router.abi, null, 2)} as const;

export const paymentRouterBytecode = ${JSON.stringify(router.bytecode.object)} as const;

/** EIP-3009 functions and events of USDC.e, testnet USDC (Circle FiatToken v2.2) and MockStablecoin. */
export const eip3009Abi = ${JSON.stringify(eip3009, null, 2)} as const;
`;
writeFileSync(`${root}packages/protocol/src/abi.ts`, out);
console.log("wrote packages/protocol/src/abi.ts");
